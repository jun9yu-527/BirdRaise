string UIRenderer::drawBar(int value, int width) {
    string bar = "[";
    int pos = (value * width) / 100;
    for (int i = 0; i < width; ++i) {
        if (i < pos) bar += "■";
        else bar += " ";
    }
    bar += "] " + to_string(value) + "%";
    return bar;
}
